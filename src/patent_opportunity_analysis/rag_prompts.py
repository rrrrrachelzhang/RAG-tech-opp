"""
RAG 报告 Prompt 管理模块：System Prompt 与 User Prompt 模板。

对齐 Ren & Zhao (2021) 技术机会发现框架的解读方法论：
  1. 按目标函数 Z 的贡献将节点/边分类
  2. 提取新颖组合 (Novel Combinations)
  3. 结合专利证据推断技术含义
  4. 综合形成可理解的机会描述
"""
from typing import List

SYSTEM_PROMPT = """\
你是一位严谨的专利分析师，正在解读基于知识网络的技术机会发现(TOD)结果。

【方法论背景】
技术机会以知识网络的连通子网形式表示。子网中的节点(技术词)和边(技术关联)\
按其对目标函数 Z 的贡献被分为以下类别：
- 新兴节点(★)：HDKN 中不存在的技术词，代表全新技术要素，对应评价指标 New_n
- 边缘节点(◇)：特征向量中心性(Eigen)低的节点，处于网络边缘，与主流技术距离远，具有突破潜力
- 特殊边(△)：仅出现在 1 篇专利中的技术关联(Min_pn 贡献者)，代表罕见但可能有突破性的组合
- 新兴边：HDKN 中不存在的边，代表全新的技术关联，对应评价指标 New_e
- 常规边(□)：历史连接强度(Con_e)高的技术关联，代表成熟可行的技术基础

**新颖组合(Novel Combinations)** = 边缘节点/新兴节点 + 特殊边/新兴边的交汇处，\
是技术机会的核心创新点。
常规边上的高频节点(如 sensor, control, robot)是连接新颖组合的桥梁，代表技术可行性基础。

你的任务是：识别子网中的新颖组合，结合专利证据推断其技术含义，最终综合为可理解的技术机会描述。

【最高级别纪律要求】
1. 绝对忠于证据：输出必须 100% 来源于提供的专利证据库，禁止使用先验知识发散。
2. 强制引证格式：
   - 每句结论性陈述后，用中括号标注**直接支撑该结论**的专利号，如 `[CN108621158B]`。
   - 若一句由多篇专利共同支撑，可并列标注，但需确保每个专利号与所述内容有明确对应关系。
   - 禁止在段落末尾堆叠与前述内容无直接对应关系的专利号。
3. 信息缺失处理：如果现有证据无法解释，请直接回答"现有证据不足"。"""


def build_user_prompt(
    nodes: List[str],
    edges_desc: List[str],
    evidence_str: str,
    score_block: str = "",
    novelty_block: str = "",
) -> str:
    """
    构建 User Prompt，注入动态数据。

    Args:
        nodes: 技术节点列表（含 ★/◇ 标记）
        edges_desc: 边描述列表（含类型、专利信息）
        evidence_str: 专利证据库字符串
        score_block: 目标函数 Z 值分解信息
        novelty_block: novelty_sources 子簇描述

    Returns:
        完整的 User Prompt 文本
    """
    nodes_str = ", ".join(nodes)
    edges_block = "\n".join(edges_desc)

    score_section = f"\n{score_block}\n" if score_block else ""
    novelty_section = f"\n{novelty_block}\n" if novelty_block else ""

    return f"""\
**【当前技术机会子网的结构数据】**
{score_section}\
- **核心技术节点 (Nodes)**：{nodes_str}
  - ★ = 新兴节点，◇ = 边缘节点
{novelty_section}\
- **技术关联 (Edges)**：
{edges_block}

**【专利证据库 (Context)】**
{evidence_str}

**【输出任务】**
请严格根据上述证据，按以下 Markdown 结构输出报告：

### 1. 技术机会命名 (不超过 15 字)
- 从新颖组合中提炼，格式：[技术手段] + [应用对象] + [目标效果]
- 必须与证据中的具体技术对应，避免空洞词汇

### 2. 重要节点与边识别
按以下类别逐一列出子网中的重要节点和边，说明其在技术机会中的角色：
- **新兴节点(★)**：列出所有标记为★的节点，说明其代表的新技术要素 [专利号]
- **边缘节点(◇)**：列出所有标记为◇的节点，解释其处于网络边缘的含义 [专利号]
- **特殊边(△)**：列出类型为 special 的边，**重点解读其唯一支撑专利的内容**——这是消歧和理解该关联具体含义的最重要线索 [专利号]
- **常规高频边(□)**：列出 con_e 最高的 2-3 条 conventional 边，说明其作为成熟技术基础的作用 [专利号]
如果某类别在当前子网中不存在，注明"本子网无此类节点/边"，并简要说明原因（如：该子网创新性由新兴边驱动而非边缘节点，或该子网无仅由单篇专利支撑的边）。

### 3. 新颖组合分析
从上述重要节点和边中，提取 2-3 个**新颖组合**：

**分析优先级（必须遵守）**：
1. **最高优先级**：若存在特殊边(△)，必须首先分析涉及该特殊边的新颖组合，因为其唯一支撑专利提供了最具体的技术语义线索
2. **次高优先级**：新兴节点子簇（如多个★节点通过 new edges 紧密互连形成的技术单元），分析该子簇作为整体代表什么新兴技术方向
3. **第三优先级**：新兴边连接的节点对

每个新颖组合的分析格式：
- `[节点A] × [节点B]（经由 [桥梁节点]）`
- 解读该组合的技术含义：这两个技术要素的结合指向什么具体应用？[专利号]
- 如果现有证据不足以判断，直接说明"现有证据不足以确定该组合的具体应用方向"

### 4. 技术机会综合解读 (3-5 句话)
- 将新颖组合归类为"技术手段"和"应用功能"两个维度
- 综合形成完整的技术机会描述，说明该机会的创新性来源和潜在价值
- 指出常规高频边所代表的成熟技术基础如何支撑上述创新
- 每句必须带专利号引用
"""
